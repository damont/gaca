"""Putting the server on the internet through a Cloudflare Tunnel (cloudflared in Docker).

Two ways: a **token** from your Cloudflare dashboard (a stable hostname you own — the normal
setup), or a **quick tunnel** (a temporary random *.trycloudflare.com address, no account — for
trying it out). cloudflared runs with host networking so it can reach the API on localhost; the
tunnel token lives in a 0600 file, never in the compose file or on a command line.
"""
from __future__ import annotations

import os
import re
from pathlib import Path

from .shell import Shell

# Pinned, multi-arch (amd64 + arm64). Same image the original gateway used.
IMAGE = "cloudflare/cloudflared:2026.7.3@sha256:e39ee8da81ad5e05d77f38d2f51c60ca51bf2a8450ac3abab50c17fdb91d91bf"
QUICK_NAME = "gaca-quick-tunnel"

_HOSTNAME = re.compile(r"[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?)+")
_TOKEN = re.compile(r"[A-Za-z0-9_=+/-]{40,4096}")
_QUICK_URL = re.compile(r"https://[a-z0-9-]+\.trycloudflare\.com")


class TunnelError(Exception):
    pass


def normalize_hostname(raw: str) -> str:
    """`https://Gaca.Example.com/` -> `gaca.example.com`; anything that is not a plain hostname raises."""
    value = raw.strip().lower()
    value = re.sub(r"^https?://", "", value).rstrip("/")
    if not _HOSTNAME.fullmatch(value):
        raise ValueError(f"{raw!r} is not a hostname like gaca.example.com")
    return value


def valid_token(raw: str) -> str:
    value = raw.strip()
    if not _TOKEN.fullmatch(value):
        raise ValueError("that does not look like a Cloudflare tunnel token (a long string from the tunnel's install command)")
    return value


def docker_ready(shell: Shell) -> bool:
    return shell.which("docker") is not None and shell.run(["docker", "info"], timeout=30).returncode == 0


def write_token_setup(config_dir: Path, token: str) -> Path:
    """Write the token file (0600) and a compose file that references it. Returns the compose path."""
    config_dir.mkdir(parents=True, exist_ok=True)
    os.chmod(config_dir, 0o700)
    token_path = config_dir / "cloudflared.token"
    token_path.write_text(token + "\n")
    os.chmod(token_path, 0o600)
    compose = config_dir / "compose.yml"
    compose.write_text(f"""# Generated by gaca-api install. cloudflared with host networking, so the tunnel's public
# hostname should point at http://localhost:<api port> in the Cloudflare dashboard.
name: gaca-tunnel
services:
  cloudflared:
    image: {IMAGE}
    network_mode: host
    user: "{os.getuid()}:{os.getgid()}"
    command: ["--no-autoupdate", "tunnel", "run", "--token-file", "/run/secrets/tunnel-token"]
    volumes:
      - ./cloudflared.token:/run/secrets/tunnel-token:ro
    restart: unless-stopped
    init: true
    read_only: true
    security_opt:
      - no-new-privileges:true
    logging:
      driver: json-file
      options:
        max-size: "10m"
        max-file: "3"
""")
    return compose


def start_token_tunnel(shell: Shell, compose: Path) -> None:
    result = shell.run(["docker", "compose", "-f", str(compose), "up", "-d"], timeout=300)
    if result.returncode != 0:
        raise TunnelError(f"docker compose failed: {(result.stderr or '').strip()[-400:]}")


def start_quick_tunnel(shell: Shell, port: int, *, wait: float = 60) -> str:
    shell.run(["docker", "rm", "-f", QUICK_NAME], timeout=30)
    started = shell.run([
        "docker", "run", "-d", "--name", QUICK_NAME, "--restart", "unless-stopped", "--network", "host",
        "--security-opt", "no-new-privileges:true", "--read-only", IMAGE,
        "tunnel", "--no-autoupdate", "--url", f"http://127.0.0.1:{port}",
    ], timeout=300)
    if started.returncode != 0:
        raise TunnelError(f"could not start the quick tunnel: {(started.stderr or '').strip()[-400:]}")
    waited = 0.0
    while waited <= wait:
        logs = shell.run(["docker", "logs", QUICK_NAME], timeout=30)
        found = _QUICK_URL.search((logs.stdout or "") + (logs.stderr or ""))
        if found:
            return found.group(0)
        shell.sleep(2)
        waited += 2
    raise TunnelError("the quick tunnel started but no address appeared; see `docker logs " + QUICK_NAME + "`")


def wait_public(shell: Shell, hostname: str, *, wait: float = 90) -> tuple[bool, int]:
    """Poll https://hostname/api/health until our API answers. (ok, last HTTP status)."""
    status, waited = 0, 0.0
    while waited <= wait:
        status, body = shell.http_get(f"https://{hostname}/api/health")
        if status == 200 and '"gaca-api"' in body:
            return True, status
        shell.sleep(3)
        waited += 3
    return False, status
