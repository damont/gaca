"""A headless Chromium, so the agent can preview a page before anyone sees it.

The gaca-artifacts skill's `preview` command renders the page in Chrome/Chromium on this machine (the one Hermes
runs on). Without a browser it falls back to "PREVIEW UNAVAILABLE", so the installer makes sure one is present,
installing the distro's Chromium package as root when needed (on Ubuntu that package installs the snap).
"""
from __future__ import annotations

from pathlib import Path

from .privilege import run_as_root
from .shell import Shell

# Keep in step with BROWSERS in skills/gaca-artifacts/scripts/artifacts.py (the names the preview looks for).
BROWSERS = ("chromium", "chromium-browser", "google-chrome", "google-chrome-stable", "chrome", "microsoft-edge")

INSTALL_SCRIPT = """#!/usr/bin/env bash
# Generated by gaca-api install: a headless Chromium for page previews.
set -euo pipefail
if command -v apt-get >/dev/null 2>&1; then
  export DEBIAN_FRONTEND=noninteractive
  apt-get update -qq
  # Debian calls it `chromium`; Ubuntu only has `chromium-browser`, which installs the snap.
  if apt-cache policy chromium 2>/dev/null | grep -q 'Candidate: [0-9]'; then
    apt-get install -y -qq chromium
  else
    apt-get install -y -qq chromium-browser
  fi
elif command -v dnf >/dev/null 2>&1; then
  dnf install -y chromium
elif command -v pacman >/dev/null 2>&1; then
  pacman -S --noconfirm --needed chromium
elif command -v zypper >/dev/null 2>&1; then
  zypper --non-interactive install chromium
elif command -v apk >/dev/null 2>&1; then
  apk add --no-cache chromium
elif command -v snap >/dev/null 2>&1; then
  snap install chromium
else
  echo "no supported package manager found; install Chrome or Chromium yourself" >&2
  exit 1
fi
"""


def find(shell: Shell) -> str | None:
    for name in BROWSERS:
        if path := shell.which(name):
            return path
    return None


def ensure(shell: Shell, script_path: Path) -> tuple[bool, str]:
    """Make sure a browser is installed. Returns (installed now, its path). Raises NeedsRoot when root is needed
    and can't be had, like every other privileged step."""
    if path := find(shell):
        return False, path
    run_as_root(shell, INSTALL_SCRIPT, script_path)
    if path := find(shell):
        return True, path
    raise RuntimeError("Chromium was installed but no `chromium` or `chromium-browser` is on PATH; "
                       "install Chrome/Chromium yourself, or re-run with --no-browser")
