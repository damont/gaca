"""Rendering the service definitions from the templates in deploy/."""
from __future__ import annotations

import re
from pathlib import Path


def render(template: str, **values: str) -> str:
    out = template
    for key, value in values.items():
        out = out.replace(f"@{key}@", value)
    leftover = re.findall(r"@[A-Z_]+@", out)
    if leftover:
        raise ValueError(f"unfilled placeholders in unit template: {sorted(set(leftover))}")
    return out


def helper_unit_files(name: str) -> tuple[tuple[str, str], str]:
    """The Hermes helper's units: ((template, installed name) for the socket and for the per-request
    service) and the socket unit's name. It is part of the gaca-api suite: installed, removed,
    reported on and restarted with it, never on its own."""
    socket = f"{name}-hermes.socket"
    return (("gaca-api-hermes.socket", socket), ("gaca-api-hermes@.service", f"{name}-hermes@.service")), socket


def system_install_script(unit_text: str, name: str, helper: dict[str, str] | None = None) -> str:
    """One script that installs and (re)starts the system service, and with it the Hermes helper's
    units (`helper`: installed file name -> text). Idempotent."""
    writes, socket = "", None
    for file_name, text in (helper or {}).items():
        writes += f"cat > /etc/systemd/system/{file_name} <<'GACA_UNIT'\n{text}GACA_UNIT\nchmod 644 /etc/systemd/system/{file_name}\n"
        if file_name.endswith(".socket"):
            socket = file_name
    sockets = f"systemctl enable {socket}\nsystemctl restart {socket}\n" if socket else ""
    return f"""#!/usr/bin/env bash
# Generated by gaca-api install. Installs and starts the {name} system service. Safe to re-run.
set -euo pipefail
cat > /etc/systemd/system/{name}.service <<'GACA_UNIT'
{unit_text}GACA_UNIT
chmod 644 /etc/systemd/system/{name}.service
{writes}systemctl daemon-reload
{sockets}systemctl enable {name}
systemctl restart {name}
echo "{name} installed and started"
"""
