"""Rendering the service definitions from the templates in deploy/."""
from __future__ import annotations

import re
from pathlib import Path


def render(template: str, **values: str) -> str:
    out = template
    for key, value in values.items():
        out = out.replace(f"@{key}@", value)
    leftover = re.findall(r"@[A-Z_]+@", out)
    if leftover:
        raise ValueError(f"unfilled placeholders in unit template: {sorted(set(leftover))}")
    return out


def system_install_script(unit_text: str, name: str) -> str:
    """One script that installs and (re)starts the system service. Idempotent."""
    return f"""#!/usr/bin/env bash
# Generated by gaca-api install. Installs and starts the {name} system service. Safe to re-run.
set -euo pipefail
cat > /etc/systemd/system/{name}.service <<'GACA_UNIT'
{unit_text}GACA_UNIT
chmod 644 /etc/systemd/system/{name}.service
systemctl daemon-reload
systemctl enable {name}
systemctl restart {name}
echo "{name} installed and started"
"""
